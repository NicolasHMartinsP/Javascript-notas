// Exercícios: Operadores e Math

//1. (Fácil) Rachando a Conta do Bar: Receba o total da mesa, o número de pessoas e a porcentagem da gorjeta e retorne quanto cada pessoa paga, arredondado para 2 casas decimais (como number).

//2. (Fácil) Estação Meteorológica: Converta uma temperatura em Celsius para Fahrenheit e Kelvin e retorne as duas em um objeto, com 2 casas decimais.

//3. (Médio) Cronômetro da Live: Receba uma duração em segundos e retorne no formato "HH:MM:SS", sempre com 2 dígitos por parte e sem zerar as horas quando passar de 24h.

//4. (Médio) Calendário da Folha de Pagamento: Diga se um ano é bissexto (divisível por 4, exceto os divisíveis por 100, a não ser que sejam divisíveis por 400) usando uma única expressão com %, && e ||, sem if.

//5. (Médio) Sorteio Justo: Crie uma função que, recebendo min, max e um valor aleatório entre 0 e 1, retorne um inteiro entre min e max (incluindo os dois) com a mesma chance para todos os números.

//6. (Difícil) Simulador de Parcelamento: Calcule a parcela de uma compra com juros compostos pela Tabela Price, recebendo valor, número de parcelas e juros mensal (%). Retorne parcela, total pago e total de juros com 2 casas, tratando o caso de juros zero.

//7. (Difícil) Ônibus que Saem Juntos: Duas linhas de ônibus saem do terminal no mesmo horário inicial "HH:MM", uma a cada A minutos e outra a cada B minutos. Retorne o MDC, o MMC (Euclides) e o horário da próxima saída conjunta, passando da meia-noite se precisar.

//8. (Difícil) Gerador de Primos: Retorne todos os números primos até n de forma eficiente (Crivo de Eratóstenes), de modo que funcione rápido para n = 100000.

//9. (Difícil) Arredondamento de Nota Fiscal: Crie uma função de arredondamento com N casas que use "meio para longe do zero" e acerte os casos em que o ponto flutuante engana o Math.round (como 1.005 com 2 casas).

//10. (Difícil) Boletim da Turma: Receba um array de notas e retorne média, mediana, desvio padrão populacional, menor nota, maior nota e amplitude, sem alterar o array original. Array vazio retorna null.
