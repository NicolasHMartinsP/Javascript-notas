// Exercícios: Objetos

//1. (Fácil) Baixa no Estoque: Receba um produto { id, nome, estoque } e a quantidade vendida e retorne um objeto novo com o estoque atualizado (nunca negativo) e a propriedade esgotado, sem alterar o original.

//2. (Fácil) Tradutor de Status: Inverta um objeto de códigos de status, transformando cada valor em chave e cada chave em valor.

//3. (Médio) Hashtags em Alta: Conte quantas vezes cada hashtag aparece (sem diferenciar maiúsculas) e retorne só as que aparecem pelo menos um número mínimo de vezes.

//4. (Médio) Painel de Pedidos por Status: Agrupe uma lista de objetos por uma chave informada, retornando um objeto em que cada valor da chave aponta para a lista de itens daquele grupo.

//5. (Médio) Conta Bancária com Métodos: Crie uma função que retorne uma conta com titular, saldo e os métodos depositar, sacar (recusando saque sem saldo) e extrato (lista das operações que deram certo), usando this.

//6. (Difícil) Configurações em Camadas: Mescle as configurações padrão de um editor com as do usuário de forma profunda: objetos aninhados são mesclados, arrays e primitivos são substituídos e valores undefined são ignorados, sem alterar os objetos recebidos.

//7. (Difícil) Achatar Objeto para Planilha: Transforme um objeto aninhado em um objeto de um nível só, com as chaves unidas por ponto. Arrays não são achatados.

//8. (Difícil) Ler Caminho em Resposta de API: Crie uma função que receba um objeto, um caminho em texto (com pontos e índices de array) e um valor padrão, e retorne o valor encontrado ou o padrão se alguma parte do caminho não existir. 0, "", false e null são válidos.

//9. (Difícil) Log de Auditoria: Compare o objeto antes e depois da edição de um cadastro e retorne o que foi adicionado, removido e alterado (com o valor antigo e o novo).

//10. (Difícil) Cache de Imagens LRU (LeetCode 146): Crie um cache com capacidade fixa e os métodos ler, salvar e chaves. Ler e salvar contam como uso, e quando o cache enche é removido o item usado há mais tempo.
