// Exercícios: Funções

//1. (Fácil) Saudação do Assistente Virtual: Retorne "Bom dia", "Boa tarde" ou "Boa noite" seguido do nome conforme a hora (5-11, 12-17, resto), usando "visitante" como parâmetro padrão quando o nome não vier.

//2. (Fácil) Fábrica de Mensagens: Crie uma função que receba um prefixo e retorne outra função que recebe um nome e monta a mensagem com aquele prefixo.

//3. (Médio) Contador de Catraca: Crie uma função que retorne um contador com incrementar, decrementar (mínimo 0), resetar e valor, com valor inicial e passo configuráveis, e sem deixar o valor acessível por fora (closure).

//4. (Médio) Pipeline de Tratamento de Texto: Crie uma função que receba várias funções e retorne uma nova função que aplica todas em sequência, da esquerda para a direita.

