//9. (Difícil) Torre de Hanói: Gere a lista de movimentos ("A->C") para levar n caixas de uma doca de origem para a de destino usando uma auxiliar, sem nunca pôr uma caixa maior sobre uma menor.

//10. (Difícil) Sistema de Eventos: Crie um emissor de eventos com on, off, once e emit, em que emit chama os callbacks registrados na ordem, repassa os dados e retorna quantos callbacks rodaram.
